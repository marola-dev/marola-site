#!/usr/bin/env python3
"""members_build: write members.html's list from marola-dev/.github's MEMBERS.md (#9).

    scripts/members_build.py                  # fetch MEMBERS.md at site/members.version, (re)write
                                              # members.html and refresh img/members/
    scripts/members_build.py --source FILE    # the same from a local MEMBERS.md (a .github checkout)
    scripts/members_build.py --check          # exit 1 if members.html or img/members/ differ from it
    scripts/members_build.py --self-test

MEMBERS.md is the org's single list of members (every Zenodo creator, ordered by first commit);
this repo keeps no copy of it, only the commit it was rendered from. Avatars are copied into
img/members/ so a visitor's browser asks GitHub for nothing; --check wants one per GitHub login and
no stray file, but not today's bytes: a new photo on GitHub shows after the next write.
"""

import argparse
import contextlib
import html
import io
import re
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PIN = ROOT / "site" / "members.version"
PAGE = ROOT / "site" / "static" / "members.html"
AVATARS = ROOT / "site" / "static" / "img" / "members"
AVATAR = "https://avatars.githubusercontent.com/{}?s=96"
RAW = "https://raw.githubusercontent.com/marola-dev/.github/{}/MEMBERS.md"
FILE = "https://github.com/marola-dev/.github/blob/main/MEMBERS.md"
ZENODO = "https://doi.org/10.5281/zenodo.23224155"
BEGIN = "<!-- members:begin, generated by scripts/members_build.py from MEMBERS.md, do not edit -->"
END = "<!-- members:end -->"
HEADER = ["Name", "Affiliation", "ORCID", "GitHub", "First commit"]
ORCID = re.compile(r"^\[(\d{4}-\d{4}-\d{4}-\d{3}[\dX])\]\(https://orcid\.org/\1\)$")
GITHUB = re.compile(r"^\[([A-Za-z0-9-]{1,39})\]\(https://github\.com/\1\)$")
COMMIT = re.compile(
    r"^\[(\d{4}-\d{2}-\d{2})\]\((https://github\.com/marola-dev/[A-Za-z0-9._-]+/commit/[0-9a-f]{40})\)$"
)
COPY = {
    "pt-BR": {
        "title": "membros",
        "lede": "as pessoas que fazem o marola, na ordem do primeiro commit de cada uma nos"
        " repositórios do projeto. quem tem ORCID também é autor do"
        f' <a href="{ZENODO}">registro do marola no Zenodo</a>.',
        "commit": "primeiro commit em {}",
        "foot": f'a lista vem do arquivo <a href="{FILE}"><code>MEMBERS.md</code></a> da organização no GitHub.'
        " para entrar na lista ou corrigir seus dados, abra um pull request nesse arquivo.",
    },
    "en": {
        "title": "Members",
        "lede": "The people who build marola, in the order of their first commit to the"
        " project's repositories. Those with an ORCID are also creators of the"
        f' <a href="{ZENODO}">marola record on Zenodo</a>.',
        "commit": "first commit on {}",
        "foot": f'The list comes from the organization\'s <a href="{FILE}"><code>MEMBERS.md</code></a> on GitHub.'
        " To join it or fix your details, open a pull request on that file.",
    },
}


class MembersError(ValueError):
    pass


def parse(text):
    """MEMBERS.md's table as [(given family, affiliation, orcid, github, (date, url))]; MembersError if malformed."""
    rows = [line.strip() for line in text.splitlines() if line.strip().startswith("|")]
    cells = [[c.strip() for c in r.strip("|").split("|")] for r in rows]
    if len(cells) < 3 or cells[0] != HEADER or not all(set(c) <= set("-: ") for c in cells[1]):
        raise MembersError(f"MEMBERS.md needs one table headed | {' | '.join(HEADER)} |")
    members = []
    for row in cells[2:]:
        if len(row) != len(HEADER):
            raise MembersError(f"a row needs {len(HEADER)} cells: {row}")
        name, aff, orcid, gh, first = row
        family, sep, given = name.partition(", ")
        if not sep or not family or not given:
            raise MembersError(f"Name is 'Family, Given', as Zenodo writes it: {name}")
        o = ORCID.match(orcid)
        g = GITHUB.match(gh)
        if orcid and not o:
            raise MembersError(f"{name}: ORCID is [id](https://orcid.org/id) or empty: {orcid}")
        if gh and not g:
            raise MembersError(
                f"{name}: GitHub is [login](https://github.com/login) or empty: {gh}"
            )
        c = COMMIT.match(first)
        if first and not c:
            raise MembersError(
                f"{name}: First commit is [YYYY-MM-DD](commit URL) or empty: {first}"
            )
        members.append(
            (f"{given} {family}", aff, o and o.group(1), g and g.group(1), c and c.groups())
        )
    if not members:
        raise MembersError("MEMBERS.md lists nobody")
    firsts = [m[4] and m[4][0] for m in members]
    dated = [d for d in firsts if d]
    if dated != sorted(dated) or firsts[: len(dated)] != dated:
        raise MembersError("rows go by first commit, oldest first, then those with none")
    return members


def initials(name):
    parts = name.split()
    return (parts[0][0] + parts[-1][0]).upper()


def sniff(data):
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    if data.startswith(b"\xff\xd8\xff"):
        return "jpg"
    raise MembersError(f"an avatar is neither PNG nor JPEG: {data[:8]!r}")


def avatar_files(folder):
    return {p.stem: p.name for p in folder.glob("*")} if folder.is_dir() else {}


def sync_avatars(logins, folder, get):
    """Download each login's avatar into folder and delete the files of logins no longer listed."""
    folder.mkdir(parents=True, exist_ok=True)
    for p in folder.glob("*"):
        if p.stem not in logins:
            p.unlink()
    for login in logins:
        data = get(login)
        for p in folder.glob(f"{login}.*"):
            p.unlink()
        (folder / f"{login}.{sniff(data)}").write_bytes(data)


def get_avatar(login):
    with urllib.request.urlopen(AVATAR.format(login), timeout=30) as r:
        return r.read()


def render(members, avatars):
    out = []
    for lang, copy in COPY.items():
        out += [
            f'    <article class="about-body" lang="{lang}">',
            f"      <h2>{copy['title']}</h2>",
            f'      <p class="lede">{copy["lede"]}</p>',
            '      <ul class="members">',
        ]
        for name, aff, orcid, gh, first in members:
            links = []
            if orcid:
                links.append(f'<a href="https://orcid.org/{orcid}">ORCID {orcid}</a>')
            if gh:
                links.append(f'<a href="https://github.com/{gh}">@{gh}</a>')
            if first:
                links.append(f'<a href="{first[1]}">{copy["commit"].format(first[0])}</a>')
            out += [
                '        <li class="member">',
                f'          <img class="member-mark" src="img/members/{avatars[gh]}" width="48" height="48" alt="" loading="lazy">'
                if gh in avatars
                else f'          <span class="member-mark" aria-hidden="true">{initials(name)}</span>',
                f'          <span class="member-name">{html.escape(name)}</span>',
                *([f'          <span class="member-aff">{html.escape(aff)}</span>'] if aff else []),
                *(
                    [f'          <span class="member-links">{" ".join(links)}</span>']
                    if links
                    else []
                ),
                "        </li>",
            ]
        out += ["      </ul>", f"      <p>{copy['foot']}</p>", "    </article>"]
        out.append("")
    return "\n".join(out[:-1])


def fetch(sha):
    with urllib.request.urlopen(RAW.format(sha), timeout=30) as r:
        return r.read().decode("utf-8")


def run(text, page, check, folder=AVATARS, get=get_avatar):
    try:
        members = parse(text)
        logins = [m[3] for m in members if m[3]]
        if not check:
            sync_avatars(logins, folder, get)
        have = avatar_files(folder)
        if set(have) != set(logins):
            raise MembersError(
                f"{folder.name}/ has avatars for {sorted(have)}, MEMBERS.md lists {sorted(logins)}:"
                " run scripts/members_build.py"
            )
        block = render(members, have)
    except MembersError as e:
        print(f"members_build: {e}", file=sys.stderr)
        return 1
    old = page.read_text(encoding="utf-8")
    if old.count(BEGIN) != 1 or old.count(END) != 1:
        print(f"members_build: {page.name} needs one '{BEGIN}' and one '{END}'", file=sys.stderr)
        return 1
    head, rest = old.split(BEGIN)
    _, tail = rest.split(END)
    new = f"{head}{BEGIN}\n{block}\n    {END}{tail}"
    if new == old:
        n = block.count('<li class="member">') // len(COPY)
        print(f"members_build: ok ({n} members)")
        return 0
    if check:
        print(
            f"members_build: {page.name} differs from MEMBERS.md, run scripts/members_build.py",
            file=sys.stderr,
        )
        return 1
    page.write_text(new, encoding="utf-8")
    print(f"members_build: wrote {page.name}")
    return 0


def self_test():
    fails = 0

    def ok(cond, label):
        nonlocal fails
        print(f"  {'ok  ' if cond else 'FAIL'} {label}")
        fails += 0 if cond else 1

    good = (
        "# Members\n\n| Name | Affiliation | ORCID | GitHub | First commit |\n|---|---|---|---|---|\n"
        "| Hoffmann, Matheus | Poli, UFRJ & co | [0009-0009-1056-7661](https://orcid.org/0009-0009-1056-7661)"
        " | [h0ffmann](https://github.com/h0ffmann) | [2026-09-05](https://github.com/marola-dev/marola/commit/"
        + "a"
        * 40
        + ") |\n"
        "| Soares da Silva Junior, Rob Kler | | | | |\n"
    )
    page = f"<main>\n    {BEGIN}\n    {END}\n</main>\n"
    png = b"\x89PNG\r\n\x1a\n" + b"0" * 8
    quiet = (contextlib.redirect_stdout, contextlib.redirect_stderr)

    def scenario(label, text, expect_ok, between=None):
        with tempfile.TemporaryDirectory() as tmp:
            out, folder = Path(tmp) / "members.html", Path(tmp) / "members"
            out.write_text(page)
            with quiet[0](io.StringIO()), quiet[1](io.StringIO()):
                run(text, out, check=False, folder=folder, get=lambda _: png)
                if between:
                    between(folder)
                rc = run(text, out, check=True, folder=folder)
            ok((rc == 0) == expect_ok, label)
            return out.read_text(), sorted(p.name for p in folder.glob("*"))

    got, files = scenario("a well-formed MEMBERS.md passes --check after a write", good, True)
    ok(files == ["h0ffmann.png"], "one avatar per GitHub login, typed by its bytes")
    ok(
        '<img class="member-mark" src="img/members/h0ffmann.png" width="48" height="48" alt=""'
        in got,
        "a member with a GitHub login shows the local avatar",
    )
    scenario(
        "an avatar missing on disk fails --check",
        good,
        False,
        between=lambda f: (f / "h0ffmann.png").unlink(),
    )
    scenario(
        "a stray avatar fails --check",
        good,
        False,
        between=lambda f: (f / "gone.png").write_bytes(png),
    )
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        (folder / "gone.jpg").write_bytes(b"x")
        (folder / "h0ffmann.jpg").write_bytes(b"x")
        sync_avatars(["h0ffmann"], folder, lambda _: png)
        ok(
            sorted(p.name for p in folder.glob("*")) == ["h0ffmann.png"],
            "a write drops avatars of logins no longer listed and a stale extension",
        )
    try:
        sniff(b"<html>")
        ok(False, "an HTML error page is not saved as an avatar")
    except MembersError:
        ok(True, "an HTML error page is not saved as an avatar")
    ok(
        got.count('<article class="about-body" lang="pt-BR">') == 1
        and got.count('<article class="about-body" lang="en">') == 1,
        "one article per language",
    )
    ok(
        '<span class="member-name">Matheus Hoffmann</span>' in got,
        "'Family, Given' shows as Given Family",
    )
    ok(
        '<span class="member-name">Rob Kler Soares da Silva Junior</span>' in got,
        "a compound family name",
    )
    ok(
        'aria-hidden="true">RJ</span>' in got and 'aria-hidden="true">MH' not in got,
        "a member with no GitHub login keeps initials (first and last word)",
    )
    ok(
        '<a href="https://orcid.org/0009-0009-1056-7661">ORCID 0009-0009-1056-7661</a>' in got,
        "ORCID link",
    )
    ok('<a href="https://github.com/h0ffmann">@h0ffmann</a>' in got, "GitHub link")
    ok("Poli, UFRJ &amp; co" in got, "the affiliation is escaped")
    ok(
        got.count("member-aff") == 2 and got.count("member-links") == 2,
        "empty cells render nothing",
    )
    ok(got.index("Matheus") < got.index("Rob Kler"), "MEMBERS.md's order is kept")
    scenario("no table fails", "# Members\n", False)
    scenario(
        "a reordered header fails",
        good.replace("| Name | Affiliation |", "| Affiliation | Name |"),
        False,
    )
    scenario(
        "a name without 'Family, Given' fails",
        good.replace("Hoffmann, Matheus", "Matheus Hoffmann"),
        False,
    )
    scenario(
        "a malformed ORCID fails", good.replace("[0009-0009-1056-7661]", "[0009-0009-1056]"), False
    )
    scenario(
        "an ORCID whose link names another id fails",
        good.replace("orcid.org/0009-0009-1056-7661", "orcid.org/0009-0009-1056-7662"),
        False,
    )
    scenario(
        "a bare GitHub login fails",
        good.replace("[h0ffmann](https://github.com/h0ffmann)", "h0ffmann"),
        False,
    )
    ok(
        f'<a href="https://github.com/marola-dev/marola/commit/{"a" * 40}">first commit on 2026-09-05</a>'
        in got,
        "the first commit links its commit",
    )
    scenario("a row with a missing cell fails", good + "| Oliveira, Elisa | | | |\n", False)
    scenario(
        "a first commit that is not a marola-dev commit URL fails",
        good.replace("marola-dev/marola/commit", "someone/else/commit"),
        False,
    )
    dated = (
        "| Oliveira, Elisa | | | | [2026-10-01](https://github.com/marola-dev/x/commit/"
        + "b" * 40
        + ") |\n"
    )
    scenario("a dated row after an undated one fails", good + dated, False)
    early = dated.replace("2026-10-01", "2026-09-01").replace("Oliveira, Elisa", "Ribeiro, Pablo")
    scenario(
        "rows out of first-commit order fail", good.replace("| Soares", early + "| Soares"), False
    )
    scenario(
        "a table with no rows fails",
        "| Name | Affiliation | ORCID | GitHub | First commit |\n|---|---|---|---|---|\n",
        False,
    )

    if fails:
        print(f"members_build self-test: {fails} failure(s)")
        return 1
    print("members_build self-test: ok")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, help="a local MEMBERS.md instead of the pinned one")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        sys.exit(self_test())
    if args.source:
        text = args.source.read_text(encoding="utf-8")
    else:
        text = fetch(PIN.read_text(encoding="utf-8").strip())
    sys.exit(run(text, PAGE, args.check))


if __name__ == "__main__":
    main()
