// Writes tests/Fixtures.elm: elm-test cannot read files, so the golden cases, the catalogs and the
// fixture boards reach the tests as string constants. Run before elm-test (npm test does).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const read = (p) => readFileSync(p, "utf8");

// Elm string literals take \u{...}, not JSON's \uXXXX, so escape by hand.
const elmString = (s) =>
  '"' +
  [...s]
    .map((c) => {
      if (c === "\\") return "\\\\";
      if (c === '"') return '\\"';
      if (c === "\n") return "\\n";
      if (c === "\r") return "\\r";
      if (c === "\t") return "\\t";
      const code = c.codePointAt(0);
      return code < 0x20 ? "\\u{" + code.toString(16).padStart(4, "0") + "}" : c;
    })
    .join("") +
  '"';

const constants = {
  golden: read(join(here, "golden.json")),
  catalogPtBr: read(join(repo, "site/i18n/pt-BR.json")),
  catalogEn: read(join(repo, "site/i18n/en.json")),
  board: read(join(repo, "site/fixtures/board.json")),
  boardSchema1: read(join(repo, "site/fixtures/board-schema1.json")),
  areas: read(join(repo, "site/areas.json")),
};

const body = Object.entries(constants)
  .map(([name, text]) => `${name} : String\n${name} =\n    ${elmString(text)}\n`)
  .join("\n\n");
writeFileSync(
  join(here, "Fixtures.elm"),
  `module Fixtures exposing (${Object.keys(constants).join(", ")})\n\n{-| Generated by tests/gen-fixtures.mjs. -}\n\n\n${body}`,
);
