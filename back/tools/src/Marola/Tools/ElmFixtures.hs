-- | Writes front/tests/Fixtures.elm: elm-test cannot read files, so the golden cases, the catalogs
-- and the fixture boards reach the tests as string constants. `npm test` runs it before elm-test.
module Marola.Tools.ElmFixtures (elmString, main, render) where

import Data.ByteString qualified as B
import Data.Char (ord)
import Data.Text (Text)
import Data.Text qualified as T
import Data.Text.Encoding qualified as TE
import Numeric (showHex)

constants :: [(Text, FilePath)]
constants =
  [ ("golden", "front/tests/golden.json"),
    ("catalogPtBr", "site/i18n/pt-BR.json"),
    ("catalogEn", "site/i18n/en.json"),
    ("board", "site/fixtures/board.json"),
    ("boardSchema1", "site/fixtures/board-schema1.json"),
    ("areas", "site/areas.json")
  ]

-- | An Elm string literal: Elm takes @\\u{...}@, not JSON's @\\uXXXX@, so it is escaped by hand.
elmString :: Text -> Text
elmString s = "\"" <> T.concatMap one s <> "\""
  where
    one '\\' = "\\\\"
    one '"' = "\\\""
    one '\n' = "\\n"
    one '\r' = "\\r"
    one '\t' = "\\t"
    one c
      | ord c < 0x20 = "\\u{" <> T.justifyRight 4 '0' (T.pack (showHex (ord c) "")) <> "}"
      | otherwise = T.singleton c

render :: [(Text, Text)] -> Text
render values =
  "module Fixtures exposing ("
    <> T.intercalate ", " (map fst values)
    <> ")\n\n{-| Generated by marola-tools elm-fixtures. -}\n\n\n"
    <> T.intercalate "\n\n" [name <> " : String\n" <> name <> " =\n    " <> elmString text <> "\n" | (name, text) <- values]

main :: IO ()
main = do
  values <- mapM (\(name, path) -> (,) name . TE.decodeUtf8 <$> B.readFile path) constants
  B.writeFile "front/tests/Fixtures.elm" (TE.encodeUtf8 (render values))
